#!/usr/bin/env python3
"""Generate include/aurora/paint/FontData.hpp - a 1-bit bitmap font atlas
for printable ASCII rendered from DejaVu Sans (bundled with matplotlib)."""
import matplotlib, os
from PIL import Image, ImageDraw, ImageFont

SIZE = 14          # pixel height target
ttf = os.path.join(os.path.dirname(matplotlib.__file__), "mpl-data", "fonts", "ttf", "DejaVuSans.ttf")
font = ImageFont.truetype(ttf, SIZE)
first, last = 32, 126
glyphs = []
ascent, descent = font.getmetrics()
line_h = ascent + descent
max_w = 0
for cp in range(first, last + 1):
    ch = chr(cp)
    bbox = font.getbbox(ch)
    img = Image.new("1", (max(bbox[2] - bbox[0], 1) + 2, line_h), 0)
    d = ImageDraw.Draw(img)
    d.text((-bbox[0] + 1, 0), ch, font=font, fill=1)
    w = img.width
    max_w = max(max_w, w)
    advance = max(int(round(font.getlength(ch))), 1)
    glyphs.append((img, w, advance))

# pack into one byte-array, glyph-major, LSB-first rows
data = []
meta = []
for img, w, adv in glyphs:
    px = img.load()
    for y in range(line_h):
        for bx in range(0, w, 8):
            byte = 0
            for bit in range(8):
                if bx + bit < w and px[bx + bit, y]:
                    byte |= 1 << bit
            data.append(byte)
    meta.append((w, adv))

with open("include/aurora/paint/FontData.hpp", "w") as f:
    f.write("#pragma once\n// Auto-generated by tools/gen_font.py - DejaVu Sans bitmap atlas\n")
    f.write("#include <cstdint>\n\nnamespace aui::font {\n")
    f.write(f"inline constexpr int kFirst = {first};\ninline constexpr int kLast = {last};\n")
    f.write(f"inline constexpr int kLineHeight = {line_h};\n")
    f.write(f"inline constexpr int kAscent = {ascent};\n")
    f.write("inline const std::uint8_t kWidths[] = {")
    f.write(",".join(str(m[0]) for m in meta))
    f.write("};\ninline const std::uint8_t kAdvances[] = {")
    f.write(",".join(str(m[1]) for m in meta))
    f.write("};\n")
    f.write("inline const std::uint8_t kBits[] = {\n")
    for i in range(0, len(data), 20):
        f.write(",".join(str(b) for b in data[i:i+20]) + ",\n")
    f.write("};\n} // namespace aui::font\n")
print("glyphs:", len(glyphs), "line_h:", line_h, "bytes:", len(data))
